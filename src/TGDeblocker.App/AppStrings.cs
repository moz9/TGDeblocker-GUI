    public static string ResolveLanguage(string? preference, CultureInfo systemUiCulture) =>
        preference == "ru" || (preference != "en" && systemUiCulture.TwoLetterISOLanguageName.Equals("ru", StringComparison.OrdinalIgnoreCase)) ? "ru" : "en";
    public static string Text(string original, string language) => language == "ru" ? original : English.TryGetValue(original, out var value) ? value : original;
    public static string Message(string original, string language)
    {
        if (language == "ru") return original;
        if (English.TryGetValue(original, out var value)) return value;
        var wait = Regex.Match(original, @"^Telegram просит повторить попытку через (\d+) с\.$");
        if (wait.Success) return $"Telegram asks you to retry in {wait.Groups[1].Value} seconds.";
        var code = Regex.Match(original, @"^Telegram отклонил запрос \(код (-?\d+)\)\.$");
        if (code.Success) return $"Telegram rejected the request (code {code.Groups[1].Value}).";
        return Regex.IsMatch(original, @"[А-Яа-яЁё]") ? "Could not complete the action. Check the connection and try again." : original;
    }
